/**
 * Fallback generator for pedestrian walkers and casual neighborhood residents.
 */
export function getGenericBanglaDialogue(
  category: string,
  state: SaveData,
  isNight: boolean,
  isRain: boolean
): string {
  if (category === 'daily_life') {
    return isRain
      ? 'বৃষ্টিতে চারপাশ ভিজে একাকার হয়ে গেছে! ছাতা নিয়ে কাজে বের হয়েছি। সাবধানে চলাফেরা করবেন।'
      : 'আলহামদুলিল্লাহ্‌, ভালোই আছি ভাই! পাড়ার সুন্দর রাস্তা ধরে হাঁটছি। আজকের দিনটা দারুণ চমৎকার!';
  }
  if (category === 'education') {
    return 'মেসের ছেলেরা সবাই খুব পরিশ্রমী আর মেধাবী। মনোযোগ দিয়ে পড়াশোনা করুন, সাফল্য নিশ্চয়ই আসবে!';
  }
  if (category === 'bangladesh_life') {
    if (!state.powerOn) {
      return 'লোডশেডিং হয়েছে ঠিকই, তবে পাড়ায় বাতাস দারুণ। কিছুক্ষণ পরই আবার বিদ্যুৎ চলে আসবে!';
    }
    return 'আমাদের পাড়াটা এখন অনেক বড় ও সুন্দর হয়েছে! নতুন পাকা সেতু আর নদী ঘাট দেখতে দূর থেকেও মানুষ আসছে।';
  }
  if (category === 'entertainment') {
    return 'বাংলাদেশ ক্রিকেট টিম যখন খেলে, সারা দেশ একসাথে জয়োল্লাস করে! এটাই বাঙালির সবচেয়ে বড় আবেগের জায়গা।';
  }
  if (category === 'food_lifestyle') {
    return 'বৃষ্টির দিনে গরম ধোঁয়া ওঠা খিচুড়ি আর বেগুন ভাজা — বাঙালির চিরন্তন সেরা তৃপ্তি!';
  }
  if (category === 'traffic_directions') {
    return 'মূল বাজার সড়ক ধরে সোজা পূর্ব দিকে গেলেই নতুন কংক্রিট সেতু আর নদীর ঘাট পাবেন। সাবধানে রাস্তা পার হবেন!';
  }
  return 'মেসের বন্ধুদের সাথে বিকেলে টংয়ের চায়ের আড্ডার চেয়ে সেরা আনন্দ দুনিয়ায় আর কিছুতে নেই ভাই!';
}
